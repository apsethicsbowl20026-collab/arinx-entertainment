import { useEffect, useRef, useState } from 'react';
import { AlertTriangle, Bot, ExternalLink, Send, User } from 'lucide-react';
import { sendChat } from '../lib/api.js';
import { SUGGESTED_QUESTIONS } from '../../shared/knowledge.js';
import { offlineWeeklyPlan } from '../../shared/planner.js';

const WELCOME = {
  role: 'assistant',
  content: 'Hi, I am Canopy. Ask me about forests, wildlife, invasive species, land restoration, India’s forests, or how AI helps protect nature. Every answer lists its sources.',
  sources: [],
};

export default function Chat({ status, request }) {
  const [messages, setMessages] = useState([WELCOME]);
  const [input, setInput] = useState('');
  const [busy, setBusy] = useState(false);
  const listRef = useRef(null);
  const lastRequest = useRef(null);

  useEffect(() => {
    if (listRef.current) listRef.current.scrollTop = listRef.current.scrollHeight;
  }, [messages, busy]);

  // Questions launched from other sections (targets, planner) are sent automatically.
  useEffect(() => {
    if (!request || request.nonce === lastRequest.current) return;
    lastRequest.current = request.nonce;
    ask(request.text, { plan: request.plan });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [request]);

  // plan (optional): the planner's result. Used to show an offline 4-week plan if no AI model answers.
  async function ask(text, { plan } = {}) {
    const question = String(text || '').trim();
    if (!question || busy) return;
    const next = [...messages, { role: 'user', content: question }];
    setMessages(next);
    setInput('');
    setBusy(true);
    const history = next.filter(m => m !== WELCOME).map(({ role, content }) => ({ role, content }));
    const data = await sendChat(history);
    const offline = plan && data.mode === 'local';
    setMessages(prev => [...prev, {
      role: 'assistant',
      content: offline
        ? `${offlineWeeklyPlan(plan)}\n\nThis plan was generated by the Canopy planner. Connect an AI model on the server for a more detailed, personalised write-up.`
        : data.reply,
      sources: offline ? [] : data.sources || [],
      mode: data.mode,
      notice: data.notice,
    }]);
    setBusy(false);
  }

  function onSubmit(e) {
    e.preventDefault();
    ask(input);
  }

  const aiOn = status?.ai?.enabled;

  return (
    <section className="section" id="chat">
      <div className="container">
        <header className="section__head">
          <h2>Ask Canopy AI</h2>
          <p>
            {aiOn
              ? <>Answers are generated by <strong>{status.ai.model}</strong> and grounded in our cited SDG 15 knowledge base.</>
              : <>Answers come from our cited SDG 15 knowledge base. Connect an AI model on the server for free-form answers.</>}
          </p>
        </header>

        <div className="chat card">
          <div className="chat__mode">
            <span className={`pill ${aiOn ? 'pill--ai' : ''}`}>
              {aiOn ? <><Bot size={14} aria-hidden="true" /> AI-powered</> : 'Offline knowledge mode'}
            </span>
          </div>
          <div className="chat__list" ref={listRef} aria-live="polite">
            {messages.map((m, i) => (
              <div className={`msg msg--${m.role}`} key={i}>
                <div className="msg__avatar" aria-hidden="true">{m.role === 'assistant' ? <Bot size={16} /> : <User size={16} />}</div>
                <div className="msg__body">
                  <div className="msg__text">{m.content}</div>
                  {m.notice && (
                    <div className="notice"><AlertTriangle size={14} aria-hidden="true" /> {m.notice}</div>
                  )}
                  {m.sources?.length > 0 && (
                    <ol className="sources">
                      {m.sources.map((s, j) => (
                        <li key={s.id + j}>
                          <span className="sources__n">[{j + 1}]</span>
                          <a href={s.url} target="_blank" rel="noreferrer">{s.title} <ExternalLink size={12} aria-hidden="true" /></a>
                          {s.publisher && <span className="muted"> · {s.publisher}</span>}
                        </li>
                      ))}
                    </ol>
                  )}
                </div>
              </div>
            ))}
            {busy && <div className="msg msg--assistant"><div className="msg__avatar"><Bot size={16} /></div><div className="msg__body"><div className="typing"><span /><span /><span /></div></div></div>}
          </div>

          <div className="chips">
            {SUGGESTED_QUESTIONS.map(q => (
              <button key={q} className="chip" disabled={busy} onClick={() => ask(q)}>{q}</button>
            ))}
          </div>

          <form className="chat__form" onSubmit={onSubmit}>
            <label htmlFor="chat-input" className="sr-only">Your question</label>
            <input
              id="chat-input"
              value={input}
              maxLength={1000}
              placeholder="Ask about forests, wildlife, soil or restoration…"
              onChange={e => setInput(e.target.value)}
            />
            <button className="btn btn--primary" type="submit" disabled={busy || !input.trim()}>
              <Send size={16} aria-hidden="true" /> Send
            </button>
          </form>
        </div>
      </div>
    </section>
  );
}
