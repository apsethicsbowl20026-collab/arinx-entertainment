import {scoreHabitat, FACTORS} from './habitat.js';
import {answerOffline, FALLBACK_ANSWER, OFFLINE_NOTE} from './knowledge.js';

const API = '/api/life-on-land/chat';
const PLEDGE_KEY = 'life-on-land-pledges';

const $ = (selector) => document.querySelector(selector);

/* ---------- Habitat health check ---------- */

const form = $('#habitat-form');
const errorBox = $('#habitat-error');
const resultBox = $('#habitat-result');

function el(tag, attrs = {}, ...children) {
  const node = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs)) {
    if (key === 'class') node.className = value;
    else node.setAttribute(key, value);
  }
  for (const child of children) node.append(child);
  return node;
}

function renderHabitat(result) {
  const ring = el('div', {class: `score-ring tone-${result.band.tone}`, 'aria-hidden': 'true'}, String(result.total));
  const heading = el('div', {},
    el('p', {class: 'muted', style: 'margin:0'}, 'Indicative health score (0–100)'),
    el('div', {class: 'score-label'}, result.band.label));

  const bars = el('ul', {class: 'bars', 'aria-label': 'Score breakdown'});
  for (const [key, meta] of Object.entries(FACTORS)) {
    const value = result.parts[key];
    const percent = Math.round((value / meta.max) * 100);
    bars.append(el('li', {},
      el('span', {}, meta.label),
      el('span', {class: 'bar', role: 'presentation'}, el('span', {style: `width:${percent}%`})),
      el('span', {}, `${value}/${meta.max}`)));
  }

  const actions = el('ol', {class: 'actions'});
  for (const action of result.actions) actions.append(el('li', {}, action));

  resultBox.replaceChildren(
    el('div', {class: 'score'}, ring, heading),
    bars,
    el('h3', {}, 'Suggested next steps'),
    actions,
    el('p', {class: 'muted', style: 'font-size:.85rem;margin:1rem 0 0'},
      'This is a rule-based estimate with visible weights, not a machine-learning prediction. Verify with local experts and field data.'));
}

form.addEventListener('submit', (event) => {
  event.preventDefault();
  const data = Object.fromEntries(new FormData(form));
  try {
    const result = scoreHabitat({
      cover: data.cover,
      trend: data.trend,
      protection: data.protection,
      invasives: data.invasives,
      landUse: data.landUse,
    });
    errorBox.hidden = true;
    renderHabitat(result);
  } catch (error) {
    errorBox.textContent = error.message;
    errorBox.hidden = false;
  }
});

// Calculate once on load so the result panel is never empty.
form.requestSubmit();

/* ---------- Land Guide chat ---------- */

const log = $('#chat-log');
const input = $('#chat-input');
const sendButton = $('#chat-send');
const badge = $('#mode-badge');
const chips = $('#chips');
const conversation = [];
let liveAvailable = false;

const SUGGESTIONS = [
  'How do camera traps use AI?',
  'What is deforestation today?',
  'How do satellite alerts work?',
  'What can I do to help?',
];

function setMode(live) {
  liveAvailable = live;
  badge.dataset.mode = live ? 'live' : 'offline';
  badge.textContent = live ? 'Live AI' : 'Offline guide';
  badge.title = live
    ? 'Answers are generated by an AI model configured for this site.'
    : 'Answers come from curated notes on this page. Configure LLM_API_KEY to enable live AI.';
}

function addBubble(role, text, note) {
  const bubble = el('div', {class: `bubble ${role}`});
  const paragraphs = String(text).split(/\n{2,}/).filter(Boolean);
  for (const paragraph of paragraphs.length ? paragraphs : ['']) bubble.append(el('p', {style: 'margin:0 0 .5rem'}, paragraph));
  bubble.lastChild?.style.setProperty('margin-bottom', '0');
  if (note) bubble.append(el('span', {class: 'note'}, note));
  log.append(bubble);
  log.scrollTop = log.scrollHeight;
  return bubble;
}

function offlineReply(question) {
  const match = answerOffline(question);
  if (!match) return {answer: FALLBACK_ANSWER, topic: null};
  return {answer: match.answer, topic: match.topic};
}

async function askLive(messages) {
  const response = await fetch(API, {
    method: 'POST',
    headers: {'Content-Type': 'application/json'},
    body: JSON.stringify({messages}),
  });
  let data;
  try {
    data = await response.json();
  } catch {
    throw new Error('not-json');
  }
  if (!response.ok) throw new Error(data.error || 'request-failed');
  return data.answer;
}

async function handleQuestion(question) {
  addBubble('user', question);
  conversation.push({role: 'user', content: question});
  const pending = addBubble('bot typing', 'Thinking…');
  sendButton.disabled = true;

  let answer;
  let note = '';
  if (liveAvailable) {
    try {
      answer = await askLive(conversation.slice(-8));
    } catch {
      // Fall back to the curated answers so the user always gets a response.
      setMode(false);
      note = 'Live AI is unavailable right now, so this answer comes from curated notes.';
    }
  }
  if (!answer) {
    const offline = offlineReply(question);
    answer = offline.answer;
    note = note || OFFLINE_NOTE;
  }

  pending.replaceWith(addBubble('bot', answer, note));
  conversation.push({role: 'assistant', content: answer});
  sendButton.disabled = false;
  input.focus();
}

$('#chat-form').addEventListener('submit', (event) => {
  event.preventDefault();
  const question = input.value.trim();
  if (!question || sendButton.disabled) return;
  input.value = '';
  handleQuestion(question);
});

for (const suggestion of SUGGESTIONS) {
  const chip = el('button', {type: 'button', class: 'chip'}, suggestion);
  chip.addEventListener('click', () => { if (!sendButton.disabled) handleQuestion(suggestion); });
  chips.append(chip);
}

addBubble('bot', 'Hello, I am the Land Guide. Ask me about forests, land restoration, wildlife, or how AI supports SDG 15.');

// Detect whether live AI is configured on the server. Static hosts and Vite return HTML here, which we treat as offline.
(async () => {
  try {
    const response = await fetch(API);
    const data = await response.json();
    setMode(Boolean(data.live));
  } catch {
    setMode(false);
  }
})();

/* ---------- Take action checklist ---------- */

const pledgeBar = $('#pledge-bar');
const pledgeCount = $('#pledge-count');
const boxes = [...document.querySelectorAll('[data-pledge]')];

function loadPledges() {
  try {
    return new Set(JSON.parse(localStorage.getItem(PLEDGE_KEY) || '[]'));
  } catch {
    return new Set();
  }
}

function renderPledges() {
  const done = boxes.filter(box => box.checked).length;
  pledgeBar.style.width = `${(done / boxes.length) * 100}%`;
  pledgeCount.textContent = `${done} of ${boxes.length} actions committed`;
}

const saved = loadPledges();
for (const box of boxes) box.checked = saved.has(box.dataset.pledge);
renderPledges();

for (const box of boxes) {
  box.addEventListener('change', () => {
    const current = boxes.filter(b => b.checked).map(b => b.dataset.pledge);
    try {
      localStorage.setItem(PLEDGE_KEY, JSON.stringify(current));
    } catch {
      // Storage may be unavailable (for example in private modes); the checklist still works for this visit.
    }
    renderPledges();
  });
}
